# S5 data check (cont.): locate the 1723/1757 count gap (published T2 cur: 1723 burgher 2395, male slave 2293; 1757 burgher 5367)
library(readxl); library(haven); library(dplyr)
source(here::here("tools", "paths.R"))
root <- dpath("P17_FvFH", "original")
o <- read_dta(file.path(root, "Statafiles", "opgaafrolle.dta"))
bt <- function(z) c(n = nrow(z), burgher = sum(z$m + z$v + z$s + z$d), sm = sum(z$sm), k = sum(z$k))
print(o %>% filter(jaar %in% 1720:1726 | jaar %in% 1754:1760) %>% group_by(jaar) %>% summarise(n = n(), b = sum(m+v+s+d), sm = sum(sm)))
z <- o[o$jaar == 1757, ]; cat("1757 dup rows burgher sum", sum(with(z[duplicated(z), ], m+v+s+d)), "\n")
cat("1757 with duplicated rows kept twice more:", bt(z)["burgher"], "\n")
x <- suppressMessages(read_excel(file.path(root, "Wealth inequality", "Time 1663 - 1757 ----  EDITED.xls"), sheet = 1))
x23 <- x %>% filter(Jaar == 1723) %>% mutate(across(c(M,V,S,D,SM), as.numeric))
cat("xls 1723 rows", nrow(x23), "distinct Van+Naam", nrow(distinct(x23, Van, Naam)), "distinct full rows", nrow(distinct(x23)), "\n")
xd <- distinct(x23, Van, Naam, M, V, S, D, SM, .keep_all = TRUE); cat("xls 1723 dedup burgher", sum(xd$M+xd$V+xd$S+xd$D, na.rm=TRUE), "sm", sum(xd$SM, na.rm=TRUE), "\n")
cat("xls 1723 ID range by half:", range(x23$ID[1:840], na.rm=TRUE), range(x23$ID[841:nrow(x23)], na.rm=TRUE), "\n")
h2 <- x23[841:nrow(x23), ]; cat("second half burgher", sum(h2$M+h2$V+h2$S+h2$D, na.rm=TRUE), "sm", sum(h2$SM, na.rm=TRUE), "; first half", sum(x23$M[1:840]+x23$V[1:840]+x23$S[1:840]+x23$D[1:840], na.rm=TRUE), "\n")
